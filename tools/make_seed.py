"""One-off import: turn the published Doc 2 page into this app's starting draft.

Reads (never writes) the old project's built page
    ../social media plan visualization/doc2-weekly-app/site/index.html
and writes
    data/seed.js   window.SEED = {...}: tiles in grid order + week themes
    media/         copies of the images/videos the draft uses

Run from this folder:  python tools/make_seed.py
Only needed again if you want a fresh draft from a rebuilt Doc 2.
"""
import json, pathlib, re, shutil, sys
from html.parser import HTMLParser

HERE = pathlib.Path(__file__).resolve().parent.parent
OLD_SITE = HERE.parent / "social media plan visualization" / "doc2-weekly-app" / "site"
MONTHS = {"Oca": 1, "Şub": 2, "Mar": 3, "Nis": 4, "May": 5, "Haz": 6, "Tem": 7, "Ağu": 8, "Eyl": 9, "Eki": 10, "Kas": 11, "Ara": 12}

# Same week themes as Doc 2 (build_doc2.py THEMES).
THEMES = [
    ("2026-11-11", "2026-11-11", "11.11 · Kendine hediye", "#E8435A"),
    ("2026-11-12", "2026-11-22", "Hediye rehberi + Efsane Cuma ısınması", "#E8435A"),
    ("2026-11-23", "2026-11-29", "Efsane Hafta", "#E8435A"),
    ("2026-11-24", "2026-11-24", "★ Öğretmenler Günü", "#F2994A"),
    ("2026-11-30", "2026-11-30", "Hediye rehberi: en çok seçilenler", "#E8435A"),
    ("2026-12-01", "2026-12-14", "Hediye zirvesi, erken sipariş", "#E8435A"),
]


def iso_from_chip(text, year=2026):
    m = re.match(r"\s*(\d{1,2})\s+(\w{3})", text)
    if not m or m.group(2) not in MONTHS:
        return ""
    return f"{year}-{MONTHS[m.group(2)]:02d}-{int(m.group(1)):02d}"


class Tiles(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tiles, self.cur, self.depth, self.grab = [], None, 0, None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        cls = (a.get("class") or "").split()
        if self.cur is None:
            if tag == "div" and "tile" in cls:
                self.cur = {"cls": cls, "attrs": a, "imgs": [], "date": "", "label": []}
                self.depth = 1
            return
        if tag == "div":
            self.depth += 1
        if tag == "img":
            self.cur["imgs"].append((a.get("src", ""), a.get("data-name", "")))
        if tag == "span" and "date" in cls:
            self.grab = "date"
        if tag == "span" and "elbl" in cls:
            self.grab = "label"

    def handle_endtag(self, tag):
        if self.cur is None:
            return
        if tag == "span" and self.grab == "date":
            self.grab = None
        if tag == "div":
            self.depth -= 1
            if self.depth == 0:
                self.tiles.append(self.cur)
                self.cur = None
                self.grab = None

    def handle_data(self, data):
        if self.cur is None or not self.grab:
            return
        if self.grab == "date":
            self.cur["date"] += data
        else:
            self.cur["label"].append(data.strip())


def main():
    page = OLD_SITE / "index.html"
    if not page.exists():
        sys.exit(f"Doc 2 page not found: {page}")
    p = Tiles()
    p.feed(page.read_text(encoding="utf-8"))

    tiles, media = [], set()
    for n, t in enumerate(p.tiles, 1):
        cls, a = t["cls"], t["attrs"]
        tile = {"id": f"s{n:03d}", "date": iso_from_chip(t["date"]), "title": a.get("data-title", ""), "note": ""}
        if "car" in cls:
            tile.update(kind="carousel", images=[{"src": s, "name": nm} for s, nm in t["imgs"]])
        elif "reel" in cls:
            tile.update(kind="reel", images=[{"src": t["imgs"][0][0], "name": a.get("data-name", "")}],
                        video=a.get("data-src", ""), match=a.get("data-match", ""))
            media.add(a.get("data-src", ""))
        else:
            words = [w for w in t["label"] if w]
            style = "later" if "later" in cls else "novid" if "novid" in cls else "soc" if "soc" in cls else "ugc"
            tile.update(kind="empty", images=[], style=style, label=" · ".join(words))
            if style == "later":
                tile["date"] = ""
                tile["label"] = t["date"].strip() + " · " + tile["label"]
        media.update(i["src"] for i in tile["images"])
        tiles.append(tile)

    out_media = HERE / "media"
    out_media.mkdir(exist_ok=True)
    for rel in sorted(m for m in media if m):
        src, dst = OLD_SITE / rel, HERE / rel
        if not dst.exists():
            shutil.copy2(src, dst)

    seed = {
        "source": "Doc 2 · Haftalık Ürün Planı (social media plan visualization)",
        "weekZero": "2026-11-02",  # Monday of "Hafta 1", as in Doc 2
        "themes": [{"from": f, "to": t, "name": nm, "color": c} for f, t, nm, c in THEMES],
        "tiles": tiles,
    }
    (HERE / "data").mkdir(exist_ok=True)
    js = "/* Generated by tools/make_seed.py from the Doc 2 page. Starting draft only. */\nwindow.SEED = " + \
         json.dumps(seed, ensure_ascii=False, indent=1) + ";\n"
    (HERE / "data" / "seed.js").write_text(js, encoding="utf-8")
    kinds = {}
    for t in tiles:
        kinds[t["kind"]] = kinds.get(t["kind"], 0) + 1
    print(f"tiles {len(tiles)} {kinds}  media files {len(media)}")


if __name__ == "__main__":
    main()
